"""Generate docs/dashboard.md from the queries in sql/dashboard/.

The spec embeds each query's SQL straight from its file, so the document,
the SQL and the exported CSVs can never drift apart.

Run on its own with:  python -m src.dashboard_spec
"""
from src import config

DASHBOARD_SQL_DIR = config.SQL_DIR / "dashboard"
SPEC_PATH = config.ROOT / "docs" / "dashboard.md"

# (query file stem, title, visual, how to build it)
COMPONENTS = {
    "KPI tiles": [
        ("kpi_01_total_revenue", "Total revenue", "KPI tile",
         "Show `total_revenue_brl` as currency (BRL), abbreviated to millions."),
        ("kpi_02_total_orders", "Total orders", "KPI tile",
         "Show `total_orders` as a whole number with thousands separators."),
        ("kpi_03_on_time_rate", "On-time delivery rate", "KPI tile",
         "Show `on_time_rate_pct` as a percentage. Subtitle: `on_time_orders` of "
         "`delivered_orders` delivered orders."),
        ("kpi_04_avg_review_score", "Average review score", "KPI tile",
         "Show `avg_review_score` out of 5. Subtitle: `reviewed_orders` reviewed orders."),
    ],
    "Charts": [
        ("chart_01_monthly_trend", "Monthly revenue and orders", "Two stacked line charts",
         "X: `year_month`. Top panel Y: `revenue_brl`. Bottom panel Y: `order_count`. "
         "Use two panels sharing the X axis, not one chart with two Y axes: the measures "
         "have different units and a dual axis invites false comparisons."),
        ("chart_02_top_categories", "Top 10 categories by revenue", "Horizontal bar chart",
         "Y: `category`, sorted by revenue descending. X: `revenue_brl`. "
         "Tooltip: `order_count`. One colour; the bars are already labelled."),
        ("chart_03_reviews_by_delivery_status", "Review scores: on-time vs late deliveries",
         "Grouped bar chart",
         "X: `review_score` (1-5). Y: `pct_of_status`. Series: `delivery_status` "
         "(On time, Late). Plot the percentage, not `order_count`: on-time orders "
         "outnumber late ones about 14 to 1, so raw counts would hide the late group."),
    ],
    "Map": [
        ("map_01_state_delivery", "On-time delivery rate by customer state",
         "Choropleth map of Brazil",
         "Location: `state_iso` (ISO 3166-2, e.g. BR-SP). Colour: `on_time_rate_pct` on a "
         "single-hue sequential scale (darker = higher). Tooltip: `order_count`, "
         "`revenue_brl`, `delivered_orders`, `avg_delivery_days`. Show `delivered_orders` "
         "in the tooltip because several states have under 150 delivered orders, so "
         "their rates are less reliable."),
    ],
}

LAYOUT = """```
+----------------+----------------+----------------+----------------+
| Total revenue  | Total orders   | On-time rate   | Avg review     |
+----------------+----------------+----------------+----------------+
| Monthly revenue and orders      | On-time delivery rate by state  |
| (two stacked line charts)       | (map)                           |
+---------------------------------+---------------------------------+
| Top 10 categories by revenue    | Review scores: on-time vs late  |
+---------------------------------+---------------------------------+
```"""


def render() -> str:
    parts = [
        "# Dashboard specification",
        "",
        "<!-- Generated by src/dashboard_spec.py from sql/dashboard/*.sql. "
        "Do not edit by hand; edit the SQL or the generator and rerun the pipeline. -->",
        "",
        "**Audience:** operations and category managers at an e-commerce marketplace.  ",
        "**Purpose:** track sales, delivery reliability and customer satisfaction, and "
        "show how delivery reliability drives satisfaction.",
        "",
        "Every component reads one CSV in `outputs/`, produced by running the SQL shown "
        "against the star schema in `data/olist.duckdb`. The dashboard has 4 KPI tiles, "
        "3 charts and 1 map.",
        "",
        "## Layout",
        "",
        LAYOUT,
        "",
        "## Shared definitions",
        "",
        "- **Revenue** is item price plus freight, in Brazilian reais (BRL).",
        "- **Orders and revenue** exclude canceled and unavailable orders.",
        "- **On time** means delivered on or before the estimated delivery date; "
        "only delivered orders count.",
        "- **Review score** uses one review per order (the most recently answered).",
        "",
    ]
    for section, components in COMPONENTS.items():
        parts += [f"## {section}", ""]
        for stem, title, visual, how in components:
            sql = (DASHBOARD_SQL_DIR / f"{stem}.sql").read_text(encoding="utf-8").strip()
            parts += [
                f"### {title}",
                "",
                f"- **Visual:** {visual}",
                f"- **Data file:** `outputs/{stem}.csv`",
                f"- **Query file:** `sql/dashboard/{stem}.sql`",
                f"- **Build:** {how}",
                "",
                "```sql",
                sql,
                "```",
                "",
            ]
    return "\n".join(parts)


def write_spec() -> None:
    documented = {stem for comps in COMPONENTS.values() for stem, *_ in comps}
    on_disk = {p.stem for p in DASHBOARD_SQL_DIR.glob("*.sql")}
    if documented != on_disk:
        raise RuntimeError(
            "Dashboard spec and sql/dashboard/ are out of sync: "
            f"undocumented={sorted(on_disk - documented)}, missing={sorted(documented - on_disk)}"
        )
    SPEC_PATH.parent.mkdir(parents=True, exist_ok=True)
    SPEC_PATH.write_text(render(), encoding="utf-8")
    print(f"  wrote {SPEC_PATH.relative_to(config.ROOT)} ({len(documented)} components)")


def main() -> None:
    write_spec()


if __name__ == "__main__":
    main()
